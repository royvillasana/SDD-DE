'use strict';

const test = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const YAML = require('yaml');
const { renderAgents, detectTools, TOOLS } = require('../lib/agents/render');
const { run, installStepAgents, loadConfig } = require('../lib/agents/cli');

const root = path.join(__dirname, '..');
const fm = (t) => YAML.parse(/^---\n([\s\S]*?)\n---/.exec(t)[1]);
const tmp = () => fs.mkdtempSync(path.join(os.tmpdir(), 'sdde-'));

// The table in docs/model-tiers.md is the contract: agent files, skills and the table must agree.
const STEPS = { 'px-screen-builder': ['balanced', 'medium', 'implement-spec'], 'px-visual-checker': ['balanced', 'medium', 'visual-verify'], 'px-reviewer': ['frontier', 'low', 'adversarial-review'], 'px-committer': ['fast', 'medium', 'commit'] };
const MODEL = { frontier: 'opus', balanced: 'sonnet', fast: 'haiku' };

test('step agents: tier/effort follow the table; each skill forks to its agent; persona agents are untouched', () => {
  const doc = fs.readFileSync(path.join(root, 'docs', 'model-tiers.md'), 'utf8');
  const files = fs.readdirSync(path.join(root, 'ai-specs', 'agents')).filter((f) => f.startsWith('px-')).map((f) => f.replace(/\.md$/, '')).sort();
  assert.deepEqual(files, Object.keys(STEPS).sort());
  for (const [name, [tier, effort, skill]] of Object.entries(STEPS)) {
    const a = fm(fs.readFileSync(path.join(root, 'ai-specs', 'agents', name + '.md'), 'utf8'));
    assert.equal(a.name, name); assert.equal(a.tier, tier); assert.equal(a.effort, effort);
    const row = doc.split('\n').find((l) => l.includes('`' + name + '`'));
    assert.ok(row && row.toLowerCase().includes(MODEL[tier]) && row.toLowerCase().includes(effort), name + ' is in the table');
    const k = fm(fs.readFileSync(path.join(root, 'ai-specs', 'skills', skill, 'SKILL.md'), 'utf8'));
    assert.equal(k.name, skill); assert.equal(k.context, 'fork'); assert.equal(k.agent, name); assert.equal(k.background, false);
    assert.ok(fs.lstatSync(path.join(root, '.claude', 'skills', skill)).isSymbolicLink(), skill + ' is linked for Claude Code');
    assert.match(fs.readFileSync(path.join(root, 'ai-specs', 'skills', skill, 'SKILL.md'), 'utf8'), /\*\*Delegation\.\*\*/);
  }
});

test('render: Claude pins models by tier; other tools inherit until configured; formats per tool', () => {
  const dir = tmp();
  for (const d of ['.cursor', '.codex', '.gemini', '.opencode', '.devin', '.github/agents']) fs.mkdirSync(path.join(dir, d), { recursive: true });
  assert.deepEqual(detectTools(dir, loadConfig(dir)), ['claude', 'cursor', 'codex', 'gemini', 'opencode', 'devin', 'copilot']);
  const rows = renderAgents({ cwd: dir, pkgDir: root, cfg: loadConfig(dir) });
  assert.equal(rows.length, Object.keys(STEPS).length * 7);
  const c = fm(fs.readFileSync(path.join(dir, '.claude/agents/px-reviewer.md'), 'utf8'));
  assert.equal(c.model, 'opus'); assert.equal(c.effort, 'low');
  assert.equal(fm(fs.readFileSync(path.join(dir, '.cursor/agents/px-reviewer.md'), 'utf8')).model, 'inherit');
  const t = fs.readFileSync(path.join(dir, '.codex/agents/px-committer.toml'), 'utf8');
  assert.match(t, /^name = "px-committer"$/m); assert.match(t, /^model_reasoning_effort = "medium"$/m);
  assert.ok(fs.existsSync(path.join(dir, '.github/agents/px-reviewer.agent.md')));
  assert.ok(fs.existsSync(path.join(dir, '.opencode/agents/px-reviewer.md')));
  assert.ok(fs.existsSync(path.join(dir, '.devin/agents/px-reviewer.md')));
  // pinned models are used, effort rides the model string where the tool defines it
  fs.mkdirSync(path.join(dir, '.sdd-de'));
  fs.writeFileSync(path.join(dir, '.sdd-de/project.yaml'), 'agents:\n  models:\n    cursor: { frontier: some-model }\n');
  renderAgents({ cwd: dir, pkgDir: root, cfg: loadConfig(dir) });
  assert.equal(fm(fs.readFileSync(path.join(dir, '.cursor/agents/px-reviewer.md'), 'utf8')).model, 'some-model[effort=low]');
});

test('render: a file the user wrote is never overwritten; old symlinks are replaced; stale generated files are removed', () => {
  const dir = tmp();
  fs.mkdirSync(path.join(dir, '.claude/agents'), { recursive: true });
  fs.writeFileSync(path.join(dir, '.claude/agents/px-committer.md'), 'mine');
  fs.symlinkSync('../../elsewhere.md', path.join(dir, '.claude/agents/px-reviewer.md'));
  fs.writeFileSync(path.join(dir, '.claude/agents/px-old.md'), '<!-- generated by sdd-de -->');
  fs.writeFileSync(path.join(dir, '.claude/agents/design-engineer.md'), 'persona');
  const rows = renderAgents({ cwd: dir, pkgDir: root, cfg: loadConfig(dir), tools: ['claude'] });
  assert.equal(fs.readFileSync(path.join(dir, '.claude/agents/px-committer.md'), 'utf8'), 'mine');
  assert.match(rows.find((r) => r.name === 'px-committer').state, /skipped/);
  assert.ok(!fs.lstatSync(path.join(dir, '.claude/agents/px-reviewer.md')).isSymbolicLink());
  assert.ok(!fs.existsSync(path.join(dir, '.claude/agents/px-old.md')));
  assert.equal(fs.readFileSync(path.join(dir, '.claude/agents/design-engineer.md'), 'utf8'), 'persona');
});

test('installStepAgents copies only the step agents next to the skills and renders them', () => {
  const dir = tmp();
  installStepAgents(dir, root, { log() {} });
  assert.deepEqual(fs.readdirSync(path.join(dir, '.sdd-de/ai-specs/agents')).sort(), Object.keys(STEPS).map((n) => n + '.md').sort());
  assert.ok(fs.existsSync(path.join(dir, '.claude/agents/px-reviewer.md')));
});

test('cli: status lists tools; an unknown tool is a clean error', () => {
  const dir = tmp(); const lines = [];
  assert.equal(run(['status', '--dir', dir], { log: (m) => lines.push(m) }), 0);
  assert.match(lines.join('\n'), /claude\s+frontier=opus/);
  const l2 = [];
  assert.equal(run(['sync', '--dir', dir, '--tools', 'nope'], { log: (m) => l2.push(m) }), 2);
  assert.match(l2.join('\n'), /Unknown tool: nope/);
  assert.ok(TOOLS.includes('claude'));
});
