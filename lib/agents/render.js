'use strict';

// Renders the neutral agent specs (ai-specs/agents/*.md: tier, effort, neutral tool names) into each coding
// tool's native subagent format. Formats come from the tools' own docs (see docs/model-tiers.md). A tier with no
// model configured for a tool is left to that tool's own default (inherit), never guessed.
const fs = require('fs');
const path = require('path');
const YAML = require('yaml');

const MARK = 'generated by sdd-de';
const TOOLS = ['claude', 'cursor', 'codex', 'gemini', 'copilot', 'opencode', 'devin'];

function parseAgent(file) {
  const text = fs.readFileSync(file, 'utf8');
  const m = /^---\n([\s\S]*?)\n---\n?([\s\S]*)$/.exec(text);
  if (!m) throw new Error(`${file}: no front matter`);
  const fm = YAML.parse(m[1]);
  for (const k of ['name', 'description', 'tier', 'effort']) if (!fm[k]) throw new Error(`${file}: missing "${k}"`);
  if (!['frontier', 'balanced', 'fast'].includes(fm.tier)) throw new Error(`${file}: tier must be frontier|balanced|fast`);
  if (!['low', 'medium', 'high'].includes(fm.effort)) throw new Error(`${file}: effort must be low|medium|high`);
  return { ...fm, body: m[2].replace(/^\n+/, '').trimEnd() + '\n', source: path.basename(file) };
}

const CLAUDE_TOOLS = { read: ['Read'], write: ['Edit', 'Write'], shell: ['Bash'], search: ['Glob', 'Grep'] };
const mdFile = (fm, body, a) => `---\n${YAML.stringify(fm).trimEnd()}\n---\n\n<!-- ${MARK} from .sdd-de/ai-specs/agents/${a.source}; edit the source and run \`sdd-de agents sync\` -->\n\n${body}`;
const modelFor = (cfg, tool, tier) => {
  const v = cfg && cfg.agents && cfg.agents.models && cfg.agents.models[tool] && cfg.agents.models[tool][tier];
  return v ? String(v) : null;
};

// tool -> { dir, file(name), render(agent, model) }
const RENDERERS = {
  claude: {
    dir: '.claude/agents', file: (n) => `${n}.md`,
    render(a, model) {
      const fm = { name: a.name, description: a.description, model: model || 'inherit', effort: a.effort };
      if (a.tools) fm.tools = a.tools.flatMap((t) => CLAUDE_TOOLS[t] || []).join(', ');
      if (a.maxTurns) fm.maxTurns = a.maxTurns;
      return mdFile(fm, a.body, a);
    },
  },
  cursor: {
    // effort rides in the model string: id[effort=high]
    dir: '.cursor/agents', file: (n) => `${n}.md`,
    render(a, model) {
      const m = model ? (model.includes('[') ? model : `${model}[effort=${a.effort}]`) : 'inherit';
      return mdFile({ name: a.name, description: a.description, model: m }, a.body, a);
    },
  },
  codex: {
    dir: '.codex/agents', file: (n) => `${n}.toml`,
    render(a, model) {
      if (a.body.includes("'''")) throw new Error(`${a.name}: body contains ''' (cannot be written as a TOML literal string)`);
      const lines = [`# ${MARK} from .sdd-de/ai-specs/agents/${a.source}; edit the source and run \`sdd-de agents sync\``,
        `name = ${JSON.stringify(a.name)}`, `description = ${JSON.stringify(a.description)}`];
      if (model) lines.push(`model = ${JSON.stringify(model)}`);
      lines.push(`model_reasoning_effort = ${JSON.stringify(a.effort)}`, `developer_instructions = '''\n${a.body}'''`);
      return lines.join('\n') + '\n';
    },
  },
  gemini: {
    dir: '.gemini/agents', file: (n) => `${n}.md`,
    render(a, model) {
      const fm = { name: a.name, description: a.description, kind: 'local', model: model || 'inherit' };
      if (a.maxTurns) fm.max_turns = a.maxTurns;
      return mdFile(fm, a.body, a);
    },
  },
  copilot: {
    dir: '.github/agents', file: (n) => `${n}.agent.md`,
    render(a, model) {
      const fm = { name: a.name, description: a.description };
      if (model) fm.model = model;
      return mdFile(fm, a.body, a);
    },
  },
  opencode: {
    // effort rides in the model variant: provider/model#variant
    dir: '.opencode/agents', file: (n) => `${n}.md`,
    render(a, model) {
      const fm = { description: a.description, mode: 'subagent' };
      if (model) fm.model = model.includes('#') ? model : `${model}#${a.effort}`;
      if (a.maxTurns) fm.steps = a.maxTurns;
      return mdFile(fm, a.body, a);
    },
  },
  devin: {
    dir: '.devin/agents', file: (n) => `${n}.md`,
    render(a, model) {
      const fm = { name: a.name, description: a.description };
      if (model) fm.model = model;
      return mdFile(fm, a.body, a);
    },
  },
};

function detectTools(cwd, cfg) {
  const want = cfg && cfg.agents && cfg.agents.tools;
  if (Array.isArray(want)) {
    const bad = want.filter((t) => !TOOLS.includes(t));
    if (bad.length) throw new Error(`agents.tools: unknown tool(s) ${bad.join(', ')} (known: ${TOOLS.join(', ')})`);
    return want;
  }
  const has = (p) => fs.existsSync(path.join(cwd, p));
  const out = ['claude'];
  if (has('.cursor')) out.push('cursor');
  if (has('.codex')) out.push('codex');
  if (has('.gemini')) out.push('gemini');
  if (has('.opencode') || has('opencode.json') || has('opencode.jsonc')) out.push('opencode');
  if (has('.devin')) out.push('devin');
  if (has('.github/agents') || has('.github/copilot-instructions.md')) out.push('copilot');
  return out;
}

const isOurs = (file) => { try { return fs.readFileSync(file, 'utf8').includes(MARK); } catch { return false; } };

// Writes every agent for every selected tool. Returns [{tool, name, file, model, state}].
function renderAgents({ cwd, pkgDir, cfg, tools }) {
  const srcDir = path.join(pkgDir, 'ai-specs', 'agents');
  if (!fs.existsSync(srcDir)) return [];
  const agents = fs.readdirSync(srcDir).filter((f) => f.startsWith('px-') && f.endsWith('.md')).sort().map((f) => parseAgent(path.join(srcDir, f)));
  const selected = tools || detectTools(cwd, cfg);
  const report = [];
  for (const tool of selected) {
    const r = RENDERERS[tool];
    const dir = path.join(cwd, r.dir);
    fs.mkdirSync(dir, { recursive: true });
    const keep = new Set();
    for (const a of agents) {
      const file = path.join(dir, r.file(a.name));
      keep.add(file);
      const model = modelFor(cfg, tool, a.tier);
      let state = 'written';
      let st = null;
      try { st = fs.lstatSync(file); } catch { /* new */ }
      if (st && st.isSymbolicLink()) fs.unlinkSync(file); // older installs linked to the neutral source
      else if (st && !isOurs(file)) state = 'skipped (a file you wrote is there)';
      if (state === 'written') fs.writeFileSync(file, r.render(a, model));
      report.push({ tool, name: a.name, file: path.relative(cwd, file), tier: a.tier, model: model || 'inherit', state });
    }
    // drop generated px-* files for agents that no longer exist
    for (const f of fs.readdirSync(dir)) {
      const p = path.join(dir, f);
      if (f.startsWith('px-') && !keep.has(p) && isOurs(p)) fs.unlinkSync(p);
    }
  }
  return report;
}

module.exports = { renderAgents, detectTools, parseAgent, RENDERERS, TOOLS, MARK };
